const TITLES: Record<LegalDocumentId, string> = {
  privacy: 'Политика обработки персональных данных',
  consent: 'Согласие на обработку персональных данных',
  cookies: 'Политика использования cookies',
};

export function generateStaticParams() {
  return LEGAL_DOCUMENTS.map((document) => ({ document }));
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ locale: string; document: string }>;
}): Promise<Metadata> {
  const { locale, document } = await params;
  if (!isLegalDocumentId(document)) return {};
  const canonicalPath = `/ru/legal/${document}`;
  return {
    robots: { index: locale === 'ru', follow: true },
    alternates: {
      canonical: locale === 'ru' ? canonicalPath : `/ru/legal/${document}`,
      languages: { ru: canonicalPath },
    },
    title: TITLES[document],
    description: `${TITLES[document]} сервиса Life OS.`,
  };
}

export default async function LegalDocumentPage({
  params,
}: {
  params: Promise<{ locale: string; document: string }>;
}) {
  const { locale, document } = await params;
  if (!isLegalDocumentId(document)) notFound();
  setRequestLocale(locale);

  if (document === 'privacy') return <PrivacyPolicy locale={locale} />;
  if (document === 'consent') return <PersonalDataConsent locale={locale} />;
  return <CookiePolicy locale={locale} />;
}

