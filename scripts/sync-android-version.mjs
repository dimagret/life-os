/**
 * Читает semver из package.json и записывает android/app/version.properties
 * для versionCode/versionName в Gradle (единый источник правды с npm).
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const pkgPath = join(root, 'package.json');
const outDir = join(root, 'android', 'app');
const outPath = join(outDir, 'version.properties');

const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
const raw = String(pkg.version ?? '0.0.0').trim();
const match = /^(\d+)\.(\d+)\.(\d+)/.exec(raw);
if (!match) {
  console.error(`sync-android-version: invalid semver in package.json: ${raw}`);
  process.exit(1);
}
const major = Number(match[1]);
const minor = Number(match[2]);
const patch = Number(match[3]);
/** Монотонный для типичных semver-бампов в пределах разумных major (Play int). */
const versionCode = major * 10000 + minor * 100 + patch;
const versionName = raw;

mkdirSync(outDir, { recursive: true });
const body = `# Generated by scripts/sync-android-version.mjs — do not edit by hand
versionCode=${versionCode}
versionName=${versionName}
`;
writeFileSync(outPath, body, 'utf8');
console.log(`sync-android-version: wrote ${outPath} (${versionCode} / ${versionName})`);
